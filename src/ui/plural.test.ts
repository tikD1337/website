import { describe, it, expect } from 'vitest'
import { plural, withPlural } from './plural'

const points = (n: number) => plural(n, 'очко', 'очка', 'очков')

describe('склонение числительных', () => {
  /* Подростки 11–14 — ловушка правила: у них всегда множественное. */
  it('одно, два–четыре, пять и больше — с исключением для 11–14', () => {
    const cases: Array<[number, string]> = [
      [1, 'очко'], [21, 'очко'], [101, 'очко'],
      [2, 'очка'], [4, 'очка'], [22, 'очка'], [54, 'очка'],
      [0, 'очков'], [5, 'очков'], [10, 'очков'], [20, 'очков'], [100, 'очков'],
      [11, 'очков'], [12, 'очков'], [14, 'очков'], [111, 'очков'], [112, 'очков'],
    ]
    for (const [n, word] of cases) expect(points(n), String(n)).toBe(word)
    expect(withPlural(54, 'команда', 'команды', 'команд')).toBe('54 команды')
  })
})
