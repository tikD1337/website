import type { Scorecard } from '../core/grading/grade'

/**
 * Слова и цвет для вердикта — общие для разбора и истории.
 *
 * Цвет здесь уместен: вердикт — это суждение, а по правилу интерфейса
 * цвет означает именно суждение. История переиспользует ту же легенду,
 * что и разбор, чтобы «зачтено полностью» не называлось двумя разными
 * словами в двух местах.
 */
export const VERDICT: Record<Scorecard['verdict'], string> = {
  full: 'Зачтено полностью',
  partial: 'Зачтено частично',
  fail: 'Не зачтено',
}

/** Оценка измерения разбита на три порога — для цвета метки. */
export function mark(score: number): string {
  return score >= 8 ? 'high' : score >= 4 ? 'mid' : 'low'
}
