import { buildTicket } from '../scenario/load'
import type { ScenarioMeta } from '../scenario/types'
import { applyInject, type InjectPatch } from '../world/world'
import type { WorldState } from '../world/types'

/**
 * Пул экземпляров и окно смены.
 *
 * Срез 5 меняет взгляд на очередь: это не вся библиотека, а окно.
 * Пул — экземпляры (сценарий плюс идентификатор), и сегодня у каждого
 * сценария ровно один экземпляр — канонический, поэтому поведение не
 * меняется. В срезе 8 у сценария станет несколько экземпляров, и
 * генератор об этом уже не узнает: он видел пул всегда.
 *
 * Правила, и каждое существует по делу:
 *
 * - **Окно смены — три тикета.** Пополнение должно быть видно: закрыл
 *   один — пришёл следующий.
 * - **Две открытые поломки на одной машине невозможны.** Экземпляр, чья
 *   машина занята, откладывается до следующего наполнения: иначе две
 *   поломки ломали бы друг друга на одной машине, и обе диагностики
 *   стали бы враньём.
 * - **Скрытие без штрафа.** Тикет уходит, экземпляр возвращается в пул
 *   и может прийти снова. Скрытие — отложенное дело, а не брошенное.
 * - **Пул может исчерпаться, и об этом говорится прямо.** Смена
 *   заканчивается после того, как пул опустел до конца: молчаливое
 *   «очередь пуста и больше не будет» читалось бы как поломка.
 * - **Поломка случается, когда тикет входит в окно, и один раз.**
 *   Пока экземпляр ждёт в пуле, его машина исправна: иначе правило
 *   «одна поломка на машину» держалось бы только в очереди, а в мире
 *   две поломки уже ломали бы друг друга. Скрытый и вернувшийся тикет
 *   не ломает машину заново — начатая починка не откатывается.
 */


export interface QueueGeneratorState {
  /** экземпляры, ждущие своей смены */
  pool: string[]
  /** тикеты текущего окна, в порядке появления */
  tickets: Ticket[]
  /** было ли объявлено, что пул исчерпан */
  exhausted: boolean
  /** экземпляры, чья поломка уже внесена в мир этой смены */
  injected: string[]
  /** сколько тикетов занимает окно смены */
  window: number
}

export const SHIFT_WINDOW = 3

export function createQueueGenerator(
  scenarioIds: string[],
  window = SHIFT_WINDOW,
): QueueGeneratorState {
  return { pool: [...scenarioIds], tickets: [], exhausted: false, injected: [], window }
}

/**
 * Выбор входящих в окно — общий для плана и наполнения.
 *
 * Меняет `g`: убирает закрытые, ставит тикеты в окно, отложенных
 * возвращает в начало пула. Возвращает id вошедших в порядке входа.
 */
function select(g: QueueGeneratorState, metas: ScenarioMeta[]): string[] {
  // Закрытые тикеты покидают окно: их место освободилось для новых.
  g.tickets = g.tickets.filter(t => t.status !== 'completed')

  /*
    Занятость машины проверяется на каждой вставке, а не один раз
    заранее.

    Множество занятых строилось до цикла и внутри него не пополнялось.
    Пока окно наполнялось с нуля, оно было пустым — и два сценария на
    одной машине въезжали в очередь вместе, после чего ломали друг
    друга, а обе диагностики становились враньём. Отложенные остаются
    в пуле и приходят, когда машина освободится: откладывание — не
    потеря.
  */
  /*
    Занята не только машина, но и общий ресурс (`resources` сценария):
    два сценария на одной ретрансляции ломали бы друг друга так же,
    как два сценария на одной машине.
  */
  const claims = (sc: ScenarioMeta) => [`device:${sc.device}`, ...(sc.resources ?? [])]
  const busy = new Set(g.tickets.flatMap(t => {
    const sc = metas.find(s => s.id === t.scenarioId)
    return sc ? claims(sc) : [`device:${t.device}`]
  }))
  const waiting: string[] = []
  const entered: string[] = []

  while (g.tickets.length < g.window && g.pool.length > 0) {
    const id = g.pool.shift()!
    const sc = metas.find(s => s.id === id)
    // Экземпляр без сценария — мусор в пуле, а не отложенное дело.
    if (!sc) continue

    if (claims(sc).some(c => busy.has(c))) {
      waiting.push(id)
      continue
    }

    for (const c of claims(sc)) busy.add(c)
    g.tickets.push(buildTicket(sc))
    entered.push(id)
  }

  // Отложенные возвращаются в начало: они ждали дольше остальных.
  g.pool.unshift(...waiting)

  g.exhausted = g.pool.length === 0 && g.tickets.length === 0
  return entered
}

/**
 * Какие сценарии войдут в окно при следующем наполнении — без наполнения.
 *
 * Стор получает поломку тикета с сервера (капсулой) до того, как тикет
 * войдёт в окно: сначала план, потом капсулы, потом `fillQueue`. Правило
 * выбора одно, поэтому план и наполнение не могут разойтись.
 */
export function planFill(g: QueueGeneratorState, metas: ScenarioMeta[]): string[] {
  return select(structuredClone(g), metas)
}

/**
 * Наполняет очередь до окна смены и ломает мир по вошедшим тикетам.
 *
 * Ведёт собственное состояние; стор зовёт его после каждого закрытия
 * или скрытия тикета. Мир — обязательный аргумент, а не отдельный шаг:
 * вход тикета в окно и поломка машины — одно событие, и вызывающий не
 * должен иметь возможности сделать одно без другого. Поломку называет
 * `injectFor` — капсула тикета с сервера.
 */
export function fillQueue(
  g: QueueGeneratorState,
  metas: ScenarioMeta[],
  world: WorldState,
  injectFor: (id: string) => InjectPatch[],
): void {
  for (const id of select(g, metas)) {
    /*
      Поломка вносится при входе в окно, а не при старте смены.

      Раньше мир ломался сразу по всей библиотеке, и откладывание
      экземпляра на занятой машине защищало только очередь: в мире
      обе поломки уже сидели на одной машине. Скрытый и вернувшийся
      тикет машину заново не ломает — начатая починка не откатывается.
    */
    if (!g.injected.includes(id)) {
      applyInject(world, injectFor(id))
      g.injected.push(id)
    }
  }
}
