import type { SessionLog } from './types'

/**
 * Видел ли техник сетевые настройки машины в этом инциденте.
 *
 * Карточка тикета показывала адрес, маску, шлюз и DNS с первой
 * секунды — и в инциденте с самоназначенным адресом `169.254.23.11`
 * с пустым шлюзом был написан прямо под номером тикета. Развилка
 * сценария («что с адресом?») решалась без единой команды. То же
 * правило, по которому просьба к заявителю открывается расследованием:
 * диагноз показывают тому, кто его нашёл.
 *
 * Считается любой запуск `ipconfig` на этой машине, успешный или нет:
 * вывод уже на экране, и прятать его в карточке после этого незачем.
 */
export function networkObserved(session: SessionLog, device: string): boolean {
  return session.commands.some(c =>
    c.device.toLowerCase() === device.toLowerCase()
    && /^ipconfig(\s|$)/i.test(c.cmdline.trim()))
}
