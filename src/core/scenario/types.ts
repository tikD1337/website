import type { InjectPatch } from '../world/world'

/**
 * Проверка состояния мира.
 *
 * Одна структура на два вопроса: «цель достигнута» и «после техника
 * осталась поломка». Универсальные проверки (адаптер остался на
 * самоназначенном адресе, DHCP отключён вручную) живут в оценке.
 * А вот «служба запущена, но тип запуска остался „отключено“» —
 * свойство конкретной поломки, и объявлять её должен сценарий.
 *
 * Вычисляется в `scenario/check.ts`: нерабочий путь падает громко,
 * потому что молчаливое «не выполнено» превращало опечатку в
 * непроходимый сценарий без всякого следа.
 */
export interface SilentFaultCheck {
  path: string
  equals?: unknown
  notEquals?: unknown
  /** массив по пути содержит значение — членство в группе, личный доступ */
  contains?: unknown
  /**
   * Выполнено хотя бы одно из вложенных условий.
   *
   * К одному результату ведут разные пути: папка откроется и через
   * группу, и через личную выдачу. Для заявителя это одно и то же
   * «заработало» — для оценки нет, и потому разделение живёт в
   * `silentFaultChecks`, а не здесь.
   */
  anyOf?: SilentFaultCheck[]
  message: string
}

/**
 * Цель сценария.
 *
 * Структура снята с разбора оригинала: у каждой цели есть заголовок,
 * человекочитаемые шаги, засчитывающие её доказательства и объяснение
 * «зачем».
 *
 * Ключевое наблюдение: процессные цели — подтвердить у заявителя,
 * написать заметку, выбрать код закрытия — стоят наравне с
 * техническими. Задача, решённая без них, даёт частичный балл.
 *
 * Доказательство бывает трёх видов и хотя бы одно обязательно:
 * запущенная команда, флаг сессии, состояние мира. Цель без
 * доказательств загрузчик не пропустит — иначе она засчитывается
 * всегда, и разбор начинает врать.
 */
export interface Objective {
  id: string
  title: string
  steps: string[]
  /** команды, засчитывающие цель; пусто у процессных целей */
  commands: string[]
  /** флаги сессии или поля тикета, которые должны быть заполнены */
  requires: string[]
  /**
   * Состояние мира, по которому видно, что цель достигнута.
   *
   * Нужно там, где результат — не команда и не флаг, а сам мир:
   * «снять блокировку» и «добавить в группу» делаются одинаково из
   * консоли и из терминала, и доказательство у них одно — учётка
   * разблокирована, членство появилось.
   *
   * Без этого поля такие цели засчитывались **всегда**: пустые списки
   * команд и флагов проходили проверку `every` тривиально, и разбор
   * утверждал, что техник сделал то, чего он не делал.
   */
  state?: SilentFaultCheck[]
  why: string
}

export interface ScriptedExchange {
  ask: string
  reply: string
}

/**
 * Персона заявителя.
 *
 * `knows` — единственное, что уходит в промпт модели, когда она
 * подключена. Корневая причина не передаётся никогда: иначе собеседник
 * через три реплики поставит диагноз сам, и тренажёр превратится
 * в подсказчик.
 */
export interface Persona {
  knows: string[]
  doesntKnow: string[]
  canDoIfAsked: string[]
  /** реплики для работы без модели */
  scripted: ScriptedExchange[]
}


/**
 * Просьба, которую техник может адресовать заявителю.
 *
 * Часть работы первой линии делается руками пользователя: убрать
 * старый пароль с телефона, выйти и войти заново. Без этого целый
 * класс правильных решений невыразим — тот самый, который отличает
 * «снял симптом» от «устранил причину».
 *
 * Объявляет просьбы сценарий, а не ядро: тренажёр не должен знать про
 * телефоны и повторные входы, он знает только, что просьба меняет мир
 * по списку путей.
 */
export interface RequesterAsk {
  id: string
  /** что говорит техник */
  ask: string
  /** что отвечает заявитель, когда сделал и это помогло */
  reply: string
  /**
   * Что отвечает заявитель, когда сделал, а не помогло.
   *
   * Заявитель сообщает то, что видит, и после просьбы тоже. Без этого
   * поля ответ был статическим: «вышла и вошла — папка открылась»
   * приходил даже тогда, когда техник попросил войти заново, не
   * добавив в группу, — то есть заявитель подтверждал непочиненное.
   *
   * Проверяется по `fixedWhen` сценария, как и подтверждение по
   * телефону. Необязательное: у просьбы, которая сама устраняет
   * причину, второго исхода не бывает.
   */
  replyIfBroken?: string
  /** как это меняет мир */
  effect: InjectPatch[]
  /**
   * Заявитель вошёл в систему заново — логин, чей билет перевыпускается.
   *
   * Отдельно от `effect`, потому что статическим патчем это не
   * выражается: повторный вход копирует **текущее** членство в билет,
   * а не записывает заранее известное значение. Отсюда и смысл просьбы:
   * без добавления в группу билет перевыпустится прежним.
   */
  relogin?: string
  /**
   * Флаг сессии, открывающий просьбу.
   *
   * Без него текст просьбы — готовый диагноз: «учётку блокирует почта
   * на телефоне» написано на кнопке, которую видно с первой секунды.
   * Условие возвращает порядок: сначала выясни причину, потом проси.
   * Это не только защита от подсказки, но и само правило работы —
   * нельзя просить то, чего не выяснил.
   */
  unlockedBy?: string
}

export interface Scenario {
  id: string
  category: string
  subcategory: string
  priority: 'P1' | 'P2' | 'P3' | 'P4'
  service: string
  summary: string
  description: string
  requester: string
  device: string
  slaResponseHours: number
  slaResolveHours: number

  /** во что сломан мир */
  inject: InjectPatch[]
  /** объяснение для разбора после закрытия — игроку заранее не показывается */
  rootCause: string
  objectives: Objective[]
  actionsToAvoid: string[]
  persona: Persona
  /** о чём можно попросить заявителя */
  asks?: RequesterAsk[]
  /** ловушки, оставленные самим техником */
  silentFaultChecks?: SilentFaultCheck[]
  /**
   * Условие, по которому заявитель поймёт, что проблема ушла.
   *
   * Заявитель судит по своей проблеме, а не по состоянию мира вообще:
   * при неполадке с печатью его не волнует сетевой адаптер. Все условия
   * должны выполниться, иначе он скажет, что всё по-прежнему.
   */
  fixedWhen: SilentFaultCheck[]
  /** что заявитель скажет: [когда заработало, когда нет] */
  confirmReplies: [string, string]

  expectedResolution: 'solved' | 'escalate' | 'not-reproducible' | 'cancelled'
}
