/**
 * Приведение ответа модели в пригодный вид.
 *
 * Модель — ненадёжный источник, и относиться к её ответу нужно как к
 * любым внешним данным: проверять, а не доверять. Найдено живой
 * проверкой на Qwen2.5: реплика начиналась по-русски и посреди фразы
 * уходила в китайский — устойчиво, на одной и той же коллокации «не
 * разбираюсь в технических…». Понижение температуры сделало это редким,
 * но не убрало: многоязычная модель всегда может соскользнуть в язык
 * обучения.
 *
 * Правило простое: **ответ, который нельзя показать, не показывается**.
 * Разговор при этом не прерывается — реплику берут заготовки сценария,
 * как при отказе модели, и техник видит плашку. Тренировка важнее
 * режима.
 *
 * Здесь же чистятся следы инструкций: модель иногда отвечает от лица
 * помощника («Как я могу вам помочь?») или пересказывает системный
 * промпт вслух. И то и другое ломает роль сильнее, чем неловкая
 * формулировка.
 */

/** Иероглифы и слоговые азбуки: китайский, японский, корейский. */
const CJK = /[぀-ヿ㐀-䶿一-鿿가-힯豈-﫿]/

/** Арабица, иврит, деванагари, тайский — то же по существу. */
const OTHER_SCRIPTS = /[֐-׿؀-ۿऀ-ॿ฀-๿]/

export interface SanitizeResult {
  ok: boolean
  text: string
  /** что именно не так — уходит в плашку и в журнал */
  reason?: string
}

/**
 * Обрезает ответ по первому срыву на чужую письменность.
 *
 * Реплика часто начинается правильно и портится к концу: у такой есть
 * годное начало, и показать его лучше, чем выбросить всё.
 *
 * Годным считается только **законченное предложение**. Это и есть
 * граница осмысленности — не длина: «Не знаю.» короткая и полноценная,
 * а «Я не разбираюсь в технических» длиннее и при этом обрывок.
 * Порог по числу символов я сначала и поставил, на чём потерял
 * законные короткие ответы.
 */
function cutAtForeign(text: string): string | null {
  const chars = [...text]
  const at = chars.findIndex(ch => CJK.test(ch) || OTHER_SCRIPTS.test(ch))
  if (at < 0) return text

  const head = chars.slice(0, at).join('')

  const lastStop = Math.max(
    head.lastIndexOf('.'), head.lastIndexOf('!'), head.lastIndexOf('?'),
    head.lastIndexOf('…'))

  // Без законченного предложения показывать нечего.
  if (lastStop < 0) return null

  const clean = head.slice(0, lastStop + 1).trim()
  return clean.length > 0 ? clean : null
}

/** Признаки того, что модель заговорила как ассистент, а не как человек. */
const ASSISTANT_MARKERS = [
  'как я могу вам помочь',
  'чем я могу помочь',
  'я не технический специалист и не могу',
  'я просто следую инструкциям',
  'согласно правилам',
  'как языковая модель',
  'я ассистент',
]

export function sanitizeReply(raw: string): SanitizeResult {
  const text = raw.trim()

  if (!text) return { ok: false, text: '', reason: 'модель вернула пустой ответ' }

  const cut = cutAtForeign(text)
  if (cut === null) {
    return {
      ok: false,
      text: '',
      reason: 'модель ответила не по-русски',
    }
  }

  const low = cut.toLowerCase()
  if (ASSISTANT_MARKERS.some(m => low.includes(m))) {
    return {
      ok: false,
      text: '',
      reason: 'модель вышла из роли заявителя',
    }
  }

  /*
    Кавычки вокруг всей реплики — модель процитировала себя вместо того,
    чтобы говорить. Видел это у Mistral: ответ приходил как «"У меня
    проблема с папкой"».
  */
  const unquoted = cut.replace(/^[«"']\s*/, '').replace(/\s*[»"']$/, '').trim()

  return {
    ok: true,
    text: unquoted,
    ...(unquoted !== text ? { reason: 'ответ модели подрезан' } : {}),
  }
}
