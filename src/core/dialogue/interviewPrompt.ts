import type { ChatMessage } from './prompt'
import type { InterviewRequest } from './types'

/**
 * Промпт интервьюера.
 *
 * Модель здесь оживляет разговор и ничего не решает: вопросы задаёт
 * движок текстом контента, оценку считает чек-лист. Поэтому от модели
 * нужно немногое и строгое — одна-две живые фразы без оценки ответа,
 * без подсказок и без новых вопросов. Оценка вслух («верно», «не
 * совсем») подменила бы разбор, подсказка — ответ.
 */
export function interviewPrompt(req: InterviewRequest): string {
  const lines = [
    `Ты проводишь собеседование на первую линию поддержки. Ты — ${req.interviewer}.`,
    'Говори по-русски, одной-двумя короткими фразами, дружелюбно и по-деловому.',
    '',
    'Что ты знаешь о компании:',
    ...req.company.map(f => `- ${f}`),
    '',
  ]
  if (req.purpose === 'react') {
    lines.push(
      `Кандидат отвечал на вопрос: «${req.question ?? ''}».`,
      'Коротко отреагируй на его ответ: поблагодари или покажи, что услышал.',
      'НЕ оценивай ответ: не говори «верно», «правильно», «не совсем», «ошибка».',
      'НЕ подсказывай и не объясняй, как было бы правильно.',
      'НЕ задавай вопросов — следующий вопрос задашь не ты.',
    )
  } else {
    lines.push(
      'Сейчас кандидат задаёт вопросы тебе. Ответь по фактам о компании.',
      'Если ответа нет в фактах, скажи, что это лучше обсудить на следующем этапе. Ничего не выдумывай.',
    )
  }
  return lines.join('\n')
}

/** Кандидат — user, интервьюер — assistant; история обрезается с начала. */
export function interviewMessages(req: InterviewRequest): ChatMessage[] {
  return [
    { role: 'system', content: interviewPrompt(req) },
    ...req.history.slice(-10).map(t => ({
      role: t.speaker === 'candidate' ? 'user' as const : 'assistant' as const,
      content: t.text,
    })),
    { role: 'user', content: req.said },
  ]
}
