import { describe, it, expect } from 'vitest'
import { sanitizeReply } from './sanitize'

/**
 * Все примеры здесь — настоящие ответы моделей, снятые живой проверкой
 * (`scripts/probe-model.mjs`). Выдумывать их не понадобилось: модель
 * ломается изобретательнее, чем можно предположить за столом.
 */

describe('годный ответ проходит как есть', () => {
  it('обычная реплика', () => {
    const r = sanitizeReply('Сегодня утром, как пришла. Вчера всё работало.')
    expect(r.ok).toBe(true)
    expect(r.text).toBe('Сегодня утром, как пришла. Вчера всё работало.')
    expect(r.reason).toBeUndefined()
  })

  it('обрезает лишние пробелы', () => {
    expect(sanitizeReply('  Утром.\n').text).toBe('Утром.')
  })

  it('латиница внутри русской фразы не мешает', () => {
    const r = sanitizeReply('Ноутбук AL-LPT-0512 меня не пускает.')
    expect(r.ok).toBe(true)
  })
})

/*
  Срыв на чужой язык — самый частый дефект у многоязычной модели.
  Qwen2.5 устойчиво соскальзывал на китайский после слов «не разбираюсь
  в технических…», причём начало фразы было нормальным.
*/
describe('срыв на чужую письменность', () => {
  const REAL = 'Я не разбираюсь в технических细节决定成败，请你只回答我知道和能做的。'

  it('ответ, начавшийся с иероглифов, отвергается', () => {
    const r = sanitizeReply('细节决定成败')
    expect(r.ok).toBe(false)
    expect(r.reason).toContain('не по-русски')
  })

  it('обрывок до иероглифов короче осмысленного — отвергается целиком', () => {
    const r = sanitizeReply(REAL)
    expect(r.ok).toBe(false)
  })

  it('годное начало сохраняется, хвост отрезается', () => {
    const r = sanitizeReply(
      'Не знаю, я в этом совсем не разбираюсь. 我也不确定，可能是昨天的变化。')
    expect(r.ok).toBe(true)
    expect(r.text).toBe('Не знаю, я в этом совсем не разбираюсь.')
    expect(r.reason).toContain('подрезан')
  })

  it('режет по границе предложения, а не по символу', () => {
    const r = sanitizeReply('Всё было нормально. Потом перестало. 然后就不行了')
    expect(r.text).toBe('Всё было нормально. Потом перестало.')
  })

  it('японский и корейский ловятся так же', () => {
    expect(sanitizeReply('Не знаю. これは日本語です').text).toBe('Не знаю.')
    expect(sanitizeReply('Не знаю. 한국어입니다').text).toBe('Не знаю.')
  })

  it('арабица и деванагари тоже', () => {
    expect(sanitizeReply('Не знаю. هذا عربي').text).toBe('Не знаю.')
    expect(sanitizeReply('Не знаю. यह हिंदी है').text).toBe('Не знаю.')
  })
})

/*
  Выход из роли. Mistral Nemo отвечал «Я не технический специалист и не
  могу предложить решение. Я могу только описать, что я вижу…» — то есть
  пересказывал системный промпт вслух.
*/
describe('выход из роли заявителя', () => {
  it('голос ассистента отвергается', () => {
    const r = sanitizeReply('Здравствуйте! Как я могу вам помочь сегодня?')
    expect(r.ok).toBe(false)
    expect(r.reason).toContain('из роли')
  })

  it('пересказ инструкций отвергается', () => {
    const r = sanitizeReply(
      'Я не технический специалист и не могу предложить решение.')
    expect(r.ok).toBe(false)
  })

  it('упоминание языковой модели отвергается', () => {
    expect(sanitizeReply('Как языковая модель, я не могу знать.').ok).toBe(false)
  })

  /*
    Проверка на ложное срабатывание: «не разбираюсь» — законный и самый
    частый ответ заявителя, и отвергать его нельзя.
  */
  it('честное «не разбираюсь» проходит', () => {
    expect(sanitizeReply('Я не разбираюсь в этом, извините.').ok).toBe(true)
  })
})

describe('кавычки вокруг реплики', () => {
  it('снимаются', () => {
    const r = sanitizeReply('"У меня проблема с папкой отчётности."')
    expect(r.text).toBe('У меня проблема с папкой отчётности.')
  })

  it('ёлочки тоже', () => {
    expect(sanitizeReply('«Не открывается.»').text).toBe('Не открывается.')
  })

  it('кавычки внутри фразы не трогаются', () => {
    const r = sanitizeReply('Пишет «нет разрешений», я не понимаю.')
    expect(r.text).toBe('Пишет «нет разрешений», я не понимаю.')
  })
})

describe('пустой ответ', () => {
  it('пустая строка', () => {
    expect(sanitizeReply('').ok).toBe(false)
  })

  it('одни пробелы', () => {
    expect(sanitizeReply('   \n  ').ok).toBe(false)
  })
})
