/**
 * Намерение реплики техника.
 *
 * Нужно ровно затем, чтобы два вопроса отвечались **миром**, а не
 * заготовленными репликами:
 *
 * 1. «Попробуйте сейчас» — ответ зависит от того, починено ли.
 *    Без этого сценарий с папкой врал бы: у него в `scripted` лежит
 *    «Попробуйте открыть сейчас» → «Так же — нет разрешений», и после
 *    верной починки заявительница продолжала бы жаловаться. Это тот же
 *    дефект «заявитель как оракул», только с обратным знаком — и он
 *    хуже, потому что наказывает за правильную работу.
 *
 * 2. «У коллег так же?» — выяснение масштаба, одно из измерений
 *    оценки. Отличить один компьютер от всего отдела обязан техник,
 *    и раз мы это оцениваем, то обязаны и распознать.
 *
 * Всё остальное — обычный вопрос.
 */

export type Intent = 'greeting' | 'retry' | 'scope' | 'other'

/** Проверить результат: «попробуйте», «получилось?», «работает теперь?». */
const RETRY = [
  'попробуй', 'проверьте', 'проверь', 'получилось', 'получается',
  'работает ли', 'заработал', 'заработало', 'войдите', 'войди',
  'откройте ещё', 'откройте еще', 'откройте сейчас', 'как сейчас',
  'ещё раз', 'еще раз', 'повторите попытку', 'зайдите',
]

/**
 * Приветствие — первая реплика почти каждого разговора.
 *
 * Найдено визуальной проверкой: «Здравствуйте, это служба поддержки»
 * получало отговорку «я в этом совсем не разбираюсь», и разговор
 * начинался с ответа мимо вопроса. На приветствие человек здоровается,
 * и это первое, что видит игрок в инструменте.
 */
const GREETING = [
  'здравствуй', 'добрый день', 'доброе утро', 'добрый вечер',
  'приветствую', 'привет', 'это служба поддержки', 'служба поддержки',
  'вас беспокоит', 'меня зовут',
]

/** Выяснение масштаба: один человек или общая система. */
const SCOPE = [
  'у коллег', 'у соседей', 'у соседки', 'у соседа', 'у других',
  'у всех', 'только у вас', 'у кого-то ещё', 'у кого-то еще',
  'в отделе так же', 'рядом так же', 'один такой', 'одна такая',
  'у остальных',
]

const norm = (s: string) => s.toLowerCase().replace(/ё/g, 'ё').replace(/\s+/g, ' ').trim()

export function detectIntent(said: string): Intent {
  const t = norm(said)

  /*
    Масштаб проверяется раньше результата: «у коллег открывается,
    попробуйте у себя» — это прежде всего вопрос про масштаб, и
    поднять флаг важнее, чем ответить про результат. Обратный порядок
    съедал бы флаг у самой естественной формулировки.
  */
  if (SCOPE.some(k => t.includes(k))) return 'scope'
  if (RETRY.some(k => t.includes(k))) return 'retry'

  /*
    Приветствие проверяется последним: «Здравствуйте, попробуйте войти»
    — это прежде всего просьба проверить, и отвечать на неё надо
    состоянием мира. Поздороваться в ответ на одно приветствие важно,
    но не важнее, чем ответить по делу.
  */
  if (GREETING.some(k => t.includes(k))) return 'greeting'
  return 'other'
}
