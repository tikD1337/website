import type { DialogueRequest } from './types'

/**
 * Сборка промпта.
 *
 * Отдельный файл, потому что это самое опасное место среза: здесь
 * решается, что именно модель узнаёт о сценарии. В промпт попадает
 * только `PersonaBrief` — сводка, из которой корневая причина вырезана
 * ещё в `brief.ts` и проверена тестом.
 *
 * Второе требование к промпту: модель обязана оставаться заявителем.
 * Языковая модель охотно «помогает» — предлагает проверить драйверы,
 * советует перезагрузиться, ставит диагноз. Заявитель так не говорит,
 * и такая подсказка обесценивает тренировку сильнее, чем прямая утечка
 * причины: она выглядит правдоподобно.
 */

export interface ChatMessage {
  role: 'system' | 'user' | 'assistant'
  content: string
}

/**
 * Параметры генерации.
 *
 * Лежат рядом с промптом, потому что описывают то же самое — как именно
 * мы просим модель говорить. Экспортируются ещё и для скрипта живой
 * проверки: он обязан спрашивать модель ровно так же, как тренажёр,
 * иначе проверяет не то.
 *
 * Температура ниже обычной намеренно. Заявителю не нужна выдумка, нужна
 * предсказуемость: разговор должен воспроизводиться, а многоязычная
 * модель тем охотнее срывается на язык обучения, чем свободнее ей
 * позволено выбирать слово. При 0.7 один и тот же прогон давал то три
 * китайские реплики из шестнадцати, то ни одной.
 *
 * Короткий ответ — тоже часть роли: длинная реплика означает, что
 * модель принялась рассуждать вместо того, чтобы отвечать.
 */
export const GENERATION = {
  max_tokens: 160,
  temperature: 0.5,
} as const

const CHANNEL_STYLE = {
  call: 'Это телефонный разговор: коротко, разговорно, без форматирования.',
  chat: 'Это чат: коротко, одно-два предложения, без формальностей.',
  mail: 'Это письмо: вежливо, но коротко, без подписи и без темы.',
} as const

export function systemPrompt(req: DialogueRequest): string {
  const { brief } = req

  const lines = [
    `Ты играешь роль сотрудника по имени ${brief.displayName}.`,
    brief.title ? `Должность: ${brief.title}, отдел: ${brief.dept}.` : '',
    '',
    'Ты обратился в службу поддержки и разговариваешь с техником.',
    'Ты НЕ технический специалист. Ты не знаешь, из-за чего возникла',
    'проблема, и не должен предполагать причину, предлагать решения,',
    'называть команды, службы, драйверы или настройки. Ты описываешь',
    'только то, что видишь на экране и что чувствуешь.',
    '',
    'Правила, которые нельзя нарушать:',
    '1. Отвечай одной-двумя фразами — это касается и самой первой',
    '   реплики. Ты человек в разговоре, а не справка.',
    '2. Никогда не ставь диагноз и не подсказывай технику, что делать.',
    '3. Если не знаешь ответа — так и скажи: «не знаю», «не разбираюсь».',
    /*
      Найдено живой проверкой: модель выдумала «с утра всё работало,
      второй день не могу» там, где проблема была с первого дня две
      недели. Прежняя формулировка запрещала выдумывать факты о
      системе — а выдуманным оказался срок. Техник строит на таком
      ответе версию и теряет время на ложном следе.
    */
    '4. Не выдумывай ничего сверх списка ниже — ни фактов о системе, ни',
    '   сроков, ни обстоятельств. Чего в списке нет, того ты не знаешь.',
    '   Спросят о времени или подробности, которых в списке нет, — так и',
    '   скажи: «точно не помню».',
    '5. Ты выполняешь просьбы техника, если они тебе по силам, и',
    '   сообщаешь, что получилось.',
    '6. Не переходи на технический язык, даже если техник его использует.',
    /*
      Найдено живой проверкой: заявительница сама предложила «выйти из
      системы и войти снова» — а это половина решения её сценария.
      Список «что могу сделать» модель прочитала как меню советов.
      Он не меню: это ответ на просьбу, а не инициатива.
    */
    '7. Список «что ты можешь сделать» — это то, что ты выполнишь, если',
    '   ПОПРОСЯТ. Сам ничего оттуда не предлагай и не перечисляй.',
    '   Придумывать решение — работа техника, не твоя.',
    /*
      Найдено живой проверкой: модель ответила по-китайски посреди
      разговора. Многоязычная модель срывается на язык обучения тем
      охотнее, чем длиннее рассуждение.
    */
    '8. Отвечай ТОЛЬКО по-русски, всегда, без единого слова на другом',
    '   языке.',
    '',
    CHANNEL_STYLE[req.channel],
    '',
  ]

  if (brief.bystander) {
    lines.push(
      'Ты НЕ тот человек, который обращался в поддержку. Тебе позвонили',
      'как коллеге. У тебя самого всё работает. О чужой проблеме и чужой',
      'учётной записи ты ничего не знаешь и знать не можешь.',
      '',
    )
  } else {
    lines.push(
      'Твоё обращение в поддержку было таким:',
      `«${brief.complaint}»`,
      '',
    )
  }

  lines.push('Что ты знаешь и можешь рассказать:')
  for (const k of brief.knows) lines.push(`- ${k}`)

  lines.push('', 'Чего ты не знаешь и не понимаешь:')
  for (const k of brief.doesntKnow) lines.push(`- ${k}`)

  /*
    Заголовок повторяет правило 7 в упор. Без него список читается как
    меню советов, и заявитель начинает подсказывать технику решение —
    видел это на живой модели.
  */
  lines.push('', 'Что ты сделаешь, ЕСЛИ ТЕХНИК ПОПРОСИТ (сам не предлагай):')
  for (const k of brief.canDoIfAsked) lines.push(`- ${k}`)

  /*
    Состояние проблемы, а не разгадка.

    Модель обязана знать, ушла ли проблема: иначе она подтвердит
    починку, которой не было, — ровно тот дефект, который дважды
    ловился на сценарных репликах. Само условие («учётка
    разблокирована») не передаётся, только результат.
  */
  lines.push('', brief.problemGone
    ? 'Прямо сейчас проблема, с которой ты обращался, БОЛЬШЕ НЕ '
      + 'ПОВТОРЯЕТСЯ. Если техник попросит проверить — проверь и '
      + 'подтверди, что заработало.'
    : 'Прямо сейчас проблема, с которой ты обращался, ВСЁ ЕЩЁ ЕСТЬ. '
      + 'Если техник попросит проверить — проверь и скажи, что ничего '
      + 'не изменилось. Не говори, что заработало, пока это не так.')

  return lines.filter(l => l !== undefined).join('\n')
}

/** История разговора в формате чата: техник — user, собеседник — assistant. */
export function buildMessages(req: DialogueRequest): ChatMessage[] {
  const out: ChatMessage[] = [{ role: 'system', content: systemPrompt(req) }]

  /*
    История обрезается: длинный разговор раздувает запрос, а контекст
    последних реплик для правдоподобия достаточен. Обрезаем с начала,
    оставляя свежее.
  */
  for (const t of req.history.slice(-12)) {
    out.push({
      role: t.speaker === 'technician' ? 'user' : 'assistant',
      content: t.text,
    })
  }

  out.push({ role: 'user', content: req.said })
  return out
}
