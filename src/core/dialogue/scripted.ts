import { detectIntent } from './intent'
import type { DialogueRequest, DialogueReply, PersonaBrief } from './types'

/**
 * Собеседник без модели.
 *
 * Работает всегда: оффлайн, без ключа, без Ollama — это база, а не
 * запасной путь. Модель, когда она есть, отвечает живее; отсутствие
 * модели не должно лишать тренажёр разговора вообще.
 *
 * Случайности здесь нет нигде. Одинаковый разговор обязан
 * воспроизводиться одинаково, иначе тест на прохождение инцидента
 * становится недетерминированным — то же правило, по которому номера
 * инцидентов считаются хешем, а не датой.
 */

const STOP = new Set([
  'что', 'как', 'это', 'вас', 'вам', 'ваш', 'ваша', 'ваше', 'ваши',
  'меня', 'мне', 'есть', 'быть', 'было', 'были', 'для', 'или', 'если',
  'когда', 'где', 'кто', 'чем', 'чего', 'там', 'тут', 'уже', 'ещё',
  'еще', 'так', 'тоже', 'сейчас', 'пожалуйста', 'скажите', 'можете',
  'можно', 'надо', 'нужно', 'просто', 'очень',
])

const norm = (s: string) => s.toLowerCase().replace(/[^\p{L}\p{N}\s]/gu, ' ')

/** Все слова нормализованной фразы. */
function allWords(s: string): string[] {
  return norm(s).split(/\s+/).filter(Boolean)
}

/** Значимые слова: от четырёх букв, без служебных. */
function words(s: string): string[] {
  return allWords(s).filter(w => w.length >= 4 && !STOP.has(w))
}

/**
 * Схожесть двух фраз — доля общих значимых слов.
 *
 * Считается от длины **заготовки**, а не запроса: техник может задать
 * вопрос длиннее, чем заготовленный, и не должен за это терять
 * совпадение. Сравнение по началу слова ловит падежи без морфологии,
 * которую оффлайн взять негде.
 */
export function similarity(said: string, ask: string): number {
  const a = words(ask)

  /*
    Заготовка целиком из коротких слов — «У вас так же?», «Кто это?».
    Значимых слов в ней нет, и по обычному правилу она не совпадала бы
    ни с чем, то есть была бы мёртвой. Такие сопоставляются строго:
    все слова на месте или не совпало вовсе. Частичное совпадение по
    двум-трём служебным словам не значит ничего.
  */
  if (a.length === 0) {
    const short = allWords(ask)
    if (short.length === 0) return 0

    const said_ = allWords(said)
    return short.every(w => said_.includes(w)) ? 1 : 0
  }

  const said_ = words(said)
  const hits = a.filter(w => said_.some(s => s.startsWith(w) || w.startsWith(s)))
  return hits.length / a.length
}

/** Порог: ниже него совпадение случайно и ответ был бы не к месту. */
const MATCH = 0.5

/**
 * Отговорки, когда вопрос не распознан.
 *
 * Выбираются по длине истории, а не случайно: разговор
 * воспроизводится. Формулировки намеренно бессодержательны — персона
 * не знает разгадку и не должна изображать осведомлённость.
 */
const FALLBACKS = [
  'Не уверена, что поняла вопрос. Можете сказать попроще?',
  'Ой, я в этом совсем не разбираюсь. Что мне сделать?',
  'Не знаю, честно. Я просто работаю, ничего не настраивала.',
  'Хм. А это важно? Мне бы просто, чтобы заработало.',
]

const BYSTANDER_FALLBACKS = [
  'Не знаю, я по этому вопросу не в курсе.',
  'У меня всё как обычно. Может, лучше у него самого спросить?',
  'Извините, не моя тема — я про свои задачи только.',
]

/**
 * Ответы на вопрос о масштабе, когда заготовки у сценария нет.
 *
 * Найдено визуальной проверкой: «у коллег рядом так же?» получало общую
 * отговорку «я в этом совсем не разбираюсь» — ответ мимо вопроса.
 * Масштаб спрашивают у каждого второго инцидента, и заготовка на него
 * есть не в каждом сценарии.
 *
 * Формулировки ничего не сообщают о причине и не выдают, один это
 * человек или весь отдел: заявитель просто не смотрел. Узнать масштаб
 * по-настоящему — работа техника, а не подарок от собеседника.
 */
const SCOPE_FALLBACKS = [
  'Не знаю, не спрашивала. Мне бы со своим разобраться.',
  'Специально не смотрела. Могу спросить у соседки, если нужно.',
  'Честно, не обращала внимания — я только про себя говорю.',
]

/**
 * Ответ на реплику техника из заготовок сценария.
 *
 * Порядок важен: сначала намерение, потом заготовки. Вопрос «работает
 * теперь?» обязан отвечаться состоянием мира, даже когда среди
 * заготовок есть похожая пара — иначе заявитель жалуется на
 * починенное.
 */
export function scriptedReply(req: DialogueRequest): DialogueReply {
  const { brief, said } = req
  const intent = detectIntent(said)

  if (intent === 'retry') {
    const [good, bad] = brief.confirmReplies
    return { text: brief.problemGone ? good : bad, source: 'scripted' }
  }

  const best = bestMatch(brief, said)
  if (best) return { text: best, source: 'scripted' }

  /*
    На приветствие человек здоровается. Отвечаем до отговорок, но после
    заготовок: если у сценария есть своя реплика на эту фразу, она
    точнее нашей общей.

    Заявитель при этом называет свою жалобу — тем же, что уже написано
    в тикете. Разгадки здесь нет: `knows` проверено тестом на утечку.
  */
  if (intent === 'greeting') {
    return { text: greetingFor(brief), source: 'scripted' }
  }

  /*
    Отговорка по теме вопроса.

    Найдено визуальной проверкой: «у коллег рядом так же?» получало
    общее «я в этом совсем не разбираюсь» — ответ мимо вопроса.
    Масштаб спрашивают едва ли не в каждом инциденте, а заготовка на
    него есть не у каждого сценария.
  */
  const pool = brief.bystander
    ? BYSTANDER_FALLBACKS
    : intent === 'scope' ? SCOPE_FALLBACKS : FALLBACKS

  const turns = req.history.filter(t => t.speaker === 'requester').length
  return { text: pool[turns % pool.length]!, source: 'scripted' }
}

/**
 * Ответ на приветствие.
 *
 * Заявитель здоровается и повторяет, с чем обратился: первое, что
 * говорит человек, взявший трубку, — своя проблема. Берётся из
 * `knows[0]` — того же списка, который уходит модели и проверен тестом
 * на утечку разгадки.
 *
 * Коллега здоровается без жалобы: ему звонят не по его беде.
 */
function greetingFor(brief: PersonaBrief): string {
  const name = brief.displayName

  if (brief.bystander) {
    return `Здравствуйте, ${name}. Слушаю вас.`
  }

  const first = brief.knows[0]
  return first
    ? `Здравствуйте! Да, это я обращалась — ${first}.`
    : 'Здравствуйте! Да, это я обращалась.'
}

/** Лучшая заготовка выше порога — или ничего. */
export function bestMatch(brief: PersonaBrief, said: string): string | null {
  let bestScore = 0
  let bestText: string | null = null

  for (const pair of brief.scripted) {
    const score = similarity(said, pair.ask)
    if (score > bestScore) {
      bestScore = score
      bestText = pair.reply
    }
  }

  return bestScore >= MATCH ? bestText : null
}
