/**
 * Интервью на первую линию Arcline.
 *
 * Вопросы — ровно то, что тренажёр отрабатывает на тикетах: здесь их
 * нужно не сделать, а объяснить. Маркеры — основы слов до чередований
 * («освобо» ловит и «освободить», и «освобождаю») и команды; слов из
 * самого вопроса среди них нет, иначе пункт засчитывался бы за пересказ
 * вопроса. Интервьюер — вымышленное лицо.
 */

const pt = (id: string, label: string, markers: string[], why: string): Point => ({ id, label, markers, why })

const EXPERIENCE_PROMPT = 'Вы закрывали {тикет}. Расскажите: в чём была причина, как вы её нашли и как убедились, что всё работает?'
const EXPERIENCE_FOLLOW_UP = 'А как вы поняли, что проблема действительно решена?'

const experience = (id: string, scenario: string, expected: string, cause: string[], found: string[], confirm: string[]): Question => ({
  id, stage: 'experience', scenario, prompt: EXPERIENCE_PROMPT, expected, followUp: EXPERIENCE_FOLLOW_UP,
  points: [
    pt('cause', 'назвали причину', cause, 'Интервьюер проверяет, что вы поняли, что сломалось, а не только нажали нужное.'),
    pt('found', 'рассказали, как нашли', found, 'Путь к причине — главное в рассказе: он показывает, как вы думаете.'),
    pt('confirm', 'сказали, чем подтвердили', confirm, 'Решено — когда подтвердил заявитель, а не когда вы закончили.'),
  ],
})

