import type { Block, Check, Course, Option } from '../core/learning/types'

/**
 * Курс «Первая линия».
 *
 * Уроки учат способу, а не разгадке конкретного тикета: номеров портов,
 * имён и адресов из сценариев здесь нет — адреса и MAC в примерах
 * условные. Каждый урок ведёт на тикет, где этот способ пригодится.
 * Команды и поля — ровно те, что показывает тренажёр.
 */

const p = (text: string): Block => ({ kind: 'p', text })
const code = (...lines: string[]): Block => ({ kind: 'code', text: lines.join('\n') })
const list = (...items: string[]): Block => ({ kind: 'list', items })

const ok = (text: string, why: string): Option => ({ text, correct: true, why })
const no = (text: string, why: string): Option => ({ text, why })

const choice = (id: string, prompt: string, ...options: Option[]): Check =>
  ({ id, kind: 'choice', prompt, options })

const text = (
  id: string, prompt: string, accept: string[], why: string,
  misses: Array<[string, string]> = [],
): Check => ({
  id, kind: 'text', prompt, accept, why,
  ...(misses.length ? { misses: misses.map(([answer, w]) => ({ answer, why: w })) } : {}),
})

